# Remove completely blank names
df = df.dropna(subset=["Name"]).copy()


# Convert names to strings and remove leading/trailing spaces
df["Name"] = df["Name"].astype(str).str.strip()


# Remove records where the cleaned name is empty
df = df[df["Name"] != ""].copy()


# Reset index after basic cleaning
df = df.reset_index(drop=True)


print(f"\nTotal valid records loaded: {len(df)}")

print("\nSample input:")
